"""Export the pinned lexical frequencies used to verify sentence boundaries."""
from itertools import groupby
import hashlib
from importlib.metadata import version
import json
from pathlib import Path
import re

from .export import lua_value
from .traditional import CONFIGS, OPENCC_VERSION


def runtime_source(directory):
    import opencc

    directory = Path(directory)
    source = directory / "upstream/jieba-dict.txt"
    manifest = json.loads((directory / "source_manifest.json").read_text())
    raw = source.read_bytes()
    digest = manifest["data/upstream/jieba-dict.txt"]["sha256"]
    if hashlib.sha256(raw).hexdigest() != digest:
        raise ValueError("Sentence boundary dictionary differs from the pinned Jieba source")
    if version("opencc") != OPENCC_VERSION:
        raise RuntimeError(f"Install build-time OpenCC=={OPENCC_VERSION}")

    han = re.compile(r"[\u3400-\u9fff]+")
    frequencies = {}
    for line in raw.decode().splitlines():
        word, frequency, _ = line.split()
        if han.fullmatch(word):
            frequencies[word] = int(frequency)
    total = sum(frequencies.values())
    # Keep single-character evidence and frequent words across all parts of speech.
    # Simplified and Traditional forms share their source frequency.
    words = {word: freq for word, freq in frequencies.items() if freq >= 3 or len(word) == 1}
    originals = tuple(words.items())
    for config in CONFIGS:
        converter = opencc.OpenCC(config)
        for word, freq in originals:
            alias = converter.convert(word)
            if han.fullmatch(alias):
                words[alias] = max(freq, words.get(alias, 0))
    header = (
        "-- Generated by shi_emoji.boundaries from pinned Jieba and OpenCC data.\n"
        "-- See THIRD_PARTY_NOTICES.md.\n"
        f"-- Jieba SHA-256: {digest}\n"
        f"return {{total={total}, max_length={max(map(len, words))}, prefixes={{\n"
    )
    buckets = []
    for prefix, entries in groupby(sorted(words.items()), key=lambda entry: entry[0][0]):
        # Each bucket is decoded on demand by the matcher. The Han suffixes
        # contain no ASCII spaces or newlines and can be empty.
        payload = "".join(f"{word[1:]} {freq}\n" for word, freq in entries)
        buckets.append(f"[{lua_value(prefix)}]=[[\n{payload}]],\n")
    return header + "".join(buckets) + "}}\n"


if __name__ == "__main__":
    Path("rime/lua/shi_emoji/boundary_data.lua").write_text(runtime_source("data"), encoding="utf-8")

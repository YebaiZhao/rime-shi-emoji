"""Encode curated descriptions and queries once; serve candidates through Rime."""
import argparse
import json
import time
from importlib.metadata import version
from pathlib import Path


def load_catalog(path):
    rows = [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]
    seen = set()
    for row in rows:
        if not row.get("emoji") or not row.get("description"):
            raise ValueError("Each catalog entry needs emoji and description")
        if row["emoji"] in seen:
            raise ValueError(f"Duplicate emoji: {row['emoji']}")
        seen.add(row["emoji"])
    if not rows:
        raise ValueError("Empty emoji catalog")
    return rows


def rank(scores, catalog, preferred, top_k):
    """Explicit user intent overrides outrank semantic neighbors; deduplicate."""
    available = {row["emoji"] for row in catalog}
    if set(preferred) - available:
        raise ValueError("Override references an emoji absent from the catalog")
    ordered = list(dict.fromkeys(preferred))
    for index in sorted(range(len(scores)), key=lambda i: (-float(scores[i]), i)):
        emoji = catalog[index]["emoji"]
        if emoji not in ordered:
            ordered.append(emoji)
    return ordered[:top_k]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=Path("data/emoji.jsonl"))
    parser.add_argument("--queries", type=Path, default=Path("data/intents.json"))
    parser.add_argument("--output", type=Path, default=Path("dist"))
    parser.add_argument("--model", default="sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2")
    parser.add_argument("--revision", help="Pin the Hugging Face model commit for repeatable builds")
    parser.add_argument("--top-k", type=int, default=6)
    args = parser.parse_args()
    if args.top_k < 1:
        parser.error("--top-k must be positive")
    catalog = load_catalog(args.catalog)
    queries = json.loads(args.queries.read_text(encoding="utf-8"))
    if not queries:
        raise ValueError("Empty intent inventory")
    from sentence_transformers import SentenceTransformer
    from pypinyin import lazy_pinyin
    import numpy as np

    started = time.perf_counter()
    model = SentenceTransformer(args.model, revision=args.revision)
    loaded = time.perf_counter()
    descriptions = model.encode([row["description"] for row in catalog], normalize_embeddings=True)
    vectors = model.encode(list(queries), normalize_embeddings=True)
    scores = np.asarray(vectors) @ np.asarray(descriptions).T
    encoded = time.perf_counter()
    # Homophones share a code: keep the best rank for each emoji, then stable-sort.
    codes = {}
    report = []
    for query, similarities in zip(queries, scores):
        code = "".join(lazy_pinyin(query)).lower()
        if not code.isascii() or not code.isalpha():
            raise ValueError(f"Intent must produce an alphabetic pinyin code: {query}")
        candidates = rank(similarities, catalog, queries[query], args.top_k)
        bucket = codes.setdefault(code, {})
        for position, emoji in enumerate(candidates):
            bucket[emoji] = max(bucket.get(emoji, 0), 10000 - position)
        report.append({"query": query, "code": code, "candidates": candidates,
                       "semantic_candidates": rank(similarities, catalog, [], args.top_k)})
    args.output.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by rime-shi-emoji; MIT", "---", "name: shi_emoji",
             'version: "0.1.0"', "sort: by_weight", "use_preset_vocabulary: false", "..."]
    for code, bucket in sorted(codes.items()):
        for emoji, weight in sorted(bucket.items(), key=lambda item: -item[1]):
            lines.append(f"{emoji}\t{code}\t{weight}")
    (args.output / "shi_emoji.dict.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (args.output / "report.json").write_text(json.dumps({
        "model": args.model, "requested_revision": args.revision,
        "sentence_transformers_version": version("sentence-transformers"),
        "model_load_seconds": loaded - started,
        "encoding_and_search_seconds": encoded - loaded,
        "emoji_count": len(catalog), "query_count": len(queries),
        "results": report,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Built {len(codes)} codes into {args.output}; review report.json before installing.")


if __name__ == "__main__":
    main()
